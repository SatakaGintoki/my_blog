test('real API: local draft recovery and optimistic concurrency', async ({ page }, testInfo) => {
  await page.goto('/admin/login')
  await page.getByLabel('用户名', { exact: true }).fill('test-admin')
  await page.getByLabel('密码', { exact: true }).fill('test-only-password-123')
  await page.getByRole('button', { name: '进入管理后台' }).click()
  await expect(page.getByRole('heading', { name: /欢迎回来/ })).toBeVisible()
  await page.goto('/admin/posts/new')
  const slug = `draft-${testInfo.project.name}-${Date.now()}`
  await page.getByLabel('文章标题', { exact: true }).fill('本地草稿恢复')
  await page.getByLabel(/文章地址 slug/).fill(slug)
  await page.getByRole('textbox', { name: 'Markdown 正文' }).fill('还没有保存到服务器的文字。')
  await expect(page.getByText('本地备份已更新')).toBeVisible()
  await page.getByRole('link', { name: '文章列表', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('文章还没有保存')
  await page.getByRole('button', { name: '备份并离开' }).click()
  await page.getByRole('link', { name: '新建文章', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('发现一份本地草稿')
  await page.getByRole('button', { name: '恢复本地草稿' }).click()
  await expect(page.getByRole('textbox', { name: 'Markdown 正文' })).toHaveValue('还没有保存到服务器的文字。')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page).toHaveURL(/admin\/posts\/\d+$/)
  await expect(page.getByLabel('文章标题', { exact: true })).toHaveValue('本地草稿恢复')
  const id = page.url().split('/').pop()!
  const token = await page.evaluate(() => sessionStorage.getItem('kuronya-session'))
  const headers = { Authorization: `Bearer ${token}` }
  const response = await page.request.get(`/api/v1/admin/posts/${id}`, { headers })
  const post = await response.json()
  const updated = await page.request.put(`/api/v1/admin/posts/${id}`, { headers, data: { title: '另一个窗口的修改', slug, content: post.content, summary: '', status: 'draft', category_id: null, tag_ids: [], expected_updated_at: post.updated_at } })
  expect(updated.ok()).toBeTruthy()
  await page.getByLabel('文章标题', { exact: true }).fill('过期窗口的修改')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('其他窗口修改')
  await expect(page.getByLabel('文章标题', { exact: true })).toHaveValue('过期窗口的修改')
  await expect(page.getByRole('button', { name: '下载本地 Markdown' })).toBeVisible()
})

